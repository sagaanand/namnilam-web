  describe('4. Cryptographic JWT Token Simulation (HS256)', () => {
    const testSecret = 'namnilam_test_secret_key_1234567890';

    function base64UrlEncode(str) {
      return Buffer.from(str)
        .toString('base64')
        .replace(/=/g, '')
        .replace(/\+/g, '-')
        .replace(/\//g, '_');
    }

    function base64UrlDecode(str) {
      let b64 = str.replace(/-/g, '+').replace(/_/g, '/');
      while (b64.length % 4) b64 += '=';
      return Buffer.from(b64, 'base64').toString('utf8');
    }

    function generateToken(payload, secret) {
      const header = { typ: 'JWT', alg: 'HS256' };
      const hStr = base64UrlEncode(JSON.stringify(header));
      const pStr = base64UrlEncode(JSON.stringify(payload));
      const sig = crypto.createHmac('sha256', secret).update(`${hStr}.${pStr}`).digest();
      const sStr = base64UrlEncode(sig);
      return `${hStr}.${pStr}.${sStr}`;
    }

    function verifyToken(token, secret) {
      const parts = token.split('.');
      if (parts.length !== 3) return null;
      const [hStr, pStr, sStr] = parts;
      const expectedSig = base64UrlEncode(crypto.createHmac('sha256', secret).update(`${hStr}.${pStr}`).digest());
      if (sStr !== expectedSig) return null;
      const payload = JSON.parse(base64UrlDecode(pStr));
      if (payload.exp && payload.exp < Math.floor(Date.now() / 1000)) return null;
      return payload;
    }

    test('Generates and verifies legitimate admin JWT token', () => {
      const now = Math.floor(Date.now() / 1000);
      const token = generateToken({
        sub: 'admin',
        role: 'Super Administrator',
        iat: now,
        exp: now + 3600
      }, testSecret);

      const verified = verifyToken(token, testSecret);
      assert.ok(verified, 'Legitimate token must verify successfully');
      assert.equal(verified.sub, 'admin');
      assert.equal(verified.role, 'Super Administrator');
    });

    test('Rejects forged token with altered secret', () => {
      const now = Math.floor(Date.now() / 1000);
      const forgedToken = generateToken({
        sub: 'admin',
        role: 'Super Administrator',
        iat: now,
        exp: now + 3600
      }, 'wrong_secret_attacker');

      const verified = verifyToken(forgedToken, testSecret);
      assert.equal(verified, null, 'Forged token must be rejected');
    });

    test('Rejects expired token', () => {
      const now = Math.floor(Date.now() / 1000);
      const expiredToken = generateToken({
        sub: 'admin',
        role: 'Super Administrator',
        iat: now - 7200,
        exp: now - 3600 // Expired 1 hour ago
      }, testSecret);

      const verified = verifyToken(expiredToken, testSecret);
      assert.equal(verified, null, 'Expired token must be rejected');
    });

    test('Rejects token with tampered payload', () => {
      const now = Math.floor(Date.now() / 1000);
      const token = generateToken({
        sub: 'user',
        role: 'Viewer',
        iat: now,
        exp: now + 3600
      }, testSecret);

      const parts = token.split('.');
      // Tamper payload to escalate role to Administrator
      const tamperedPayload = base64UrlEncode(JSON.stringify({
        sub: 'admin',
        role: 'Super Administrator',
        iat: now,
        exp: now + 3600
      }));
      const tamperedToken = `${parts[0]}.${tamperedPayload}.${parts[2]}`;

      const verified = verifyToken(tamperedToken, testSecret);
      assert.equal(verified, null, 'Tampered token must be rejected');
    });
  });

